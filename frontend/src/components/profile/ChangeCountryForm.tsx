// Convert country code to flag emoji
const getFlag = (countryCode: string): string => {
  const codePoints = countryCode
    .toUpperCase()
    .split('')
    .map((char) => 127397 + char.charCodeAt(0));
  return String.fromCodePoint(...codePoints);
};

export const ChangeCountryForm = ({ onSuccess, onCancel }: ChangeCountryFormProps) => {
  const { user, refreshUser } = useAuth();
  const [error, setError] = useState('');
  const [success, setSuccess] = useState(false);
  const [isLoading, setIsLoading] = useState(false);
  const [searchQuery, setSearchQuery] = useState('');
  const [selectedCountry, setSelectedCountry] = useState<string>(user?.country || '');
  const [isOpen, setIsOpen] = useState(false);

  const filteredCountries = useMemo(() => {
    if (!searchQuery) return COUNTRIES;
    const query = searchQuery.toLowerCase();
    return COUNTRIES.filter(
      (country) =>
        country.name.toLowerCase().includes(query) ||
        country.code.toLowerCase().includes(query)
    );
  }, [searchQuery]);

  const selectedCountryData = COUNTRIES.find((c) => c.code === selectedCountry || c.name === selectedCountry);

  const onSubmit = async (e: React.FormEvent) => {
    e.preventDefault();

    if (!selectedCountry) {
      setError('Please select a country');
      return;
    }

    setError('');
    setSuccess(false);
    setIsLoading(true);

    try {
      await authService.changeCountry(selectedCountry);
      setSuccess(true);
      await refreshUser();

      setTimeout(() => {
        onSuccess();
      }, 2000);
    } catch (err: any) {
      setError(err.message || 'Failed to change country');
    } finally {
      setIsLoading(false);
    }
  };

  return (
    <form onSubmit={onSubmit} className="space-y-4">
      {error && (
        <div className="bg-destructive/10 text-destructive text-sm p-3 rounded-md border border-destructive/20">
          {error}
        </div>
      )}

      {success && (
        <div className="bg-green-50 dark:bg-green-900/20 text-green-700 dark:text-green-400 text-sm p-3 rounded-md border border-green-200 dark:border-green-800">
          Country changed successfully!
        </div>
      )}

      <div className="space-y-2">
        <Label htmlFor="country">Country</Label>
        <div className="relative">
          <div
            className="flex h-10 w-full items-center justify-between rounded-md border border-input bg-background px-3 py-2 text-sm ring-offset-background cursor-pointer hover:bg-accent"
            onClick={() => setIsOpen(!isOpen)}
          >
            {selectedCountryData ? (
              <span className="flex items-center gap-2">
                <span className="text-xl">{getFlag(selectedCountryData.code)}</span>
                <span>{selectedCountryData.name}</span>
              </span>
            ) : (
              <span className="text-muted-foreground">Select a country...</span>
            )}
            <svg
              className={`h-4 w-4 transition-transform ${isOpen ? 'rotate-180' : ''}`}
              fill="none"
              stroke="currentColor"
              viewBox="0 0 24 24"
            >
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M19 9l-7 7-7-7" />
            </svg>
          </div>

          {isOpen && (
            <div className="absolute z-50 mt-1 w-full rounded-md border border-input bg-background shadow-lg">
              <div className="p-2 border-b">
                <Input
                  placeholder="Search countries..."
                  value={searchQuery}
                  onChange={(e) => setSearchQuery(e.target.value)}
                  className="h-8"
                  autoFocus
                />
              </div>
              <div className="max-h-60 overflow-y-auto">
                {filteredCountries.length === 0 ? (
                  <div className="p-3 text-sm text-muted-foreground text-center">
                    No countries found
                  </div>
                ) : (
                  filteredCountries.map((country) => (
                    <div
                      key={country.code}
                      className={`flex items-center gap-2 px-3 py-2 cursor-pointer hover:bg-accent ${
                        selectedCountry === country.code || selectedCountry === country.name
                          ? 'bg-accent'
                          : ''
                      }`}
                      onClick={() => {
                        setSelectedCountry(country.code);
                        setIsOpen(false);
                        setSearchQuery('');
                      }}
                    >
                      <span className="text-xl">{getFlag(country.code)}</span>
                      <span className="text-sm">{country.name}</span>
                    </div>
                  ))
                )}
              </div>
            </div>
          )}
        </div>
      </div>

      <div className="flex gap-4">
        <Button type="submit" disabled={isLoading || !selectedCountry} className="flex-1">
          {isLoading ? 'Updating Country...' : 'Update Country'}
        </Button>
        <Button type="button" variant="outline" onClick={onCancel} disabled={isLoading} className="flex-1">
          Cancel
        </Button>
      </div>
    </form>
  );
};
